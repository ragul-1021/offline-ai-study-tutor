# Support both standard JSON response and real-time streaming
@app.get("/ask")
def ask_get(question: str, stream: bool = False):
    if not question.strip():
        raise HTTPException(status_code=400, detail="Question cannot be empty.")
    messages = [{"role": "user", "content": question}]
    if stream:
        return StreamingResponse(
            stream_generator(messages),
            media_type="text/plain; charset=utf-8",
            headers=STREAM_HEADERS,
        )

    response = model.create_chat_completion(messages=messages, max_tokens=256)
    answer = response["choices"][0]["message"]["content"]
    return {"question": question, "answer": answer}


@app.post("/ask")
def ask_post(request: QueryRequest):
    if not request.question.strip():
        raise HTTPException(status_code=400, detail="Question cannot be empty.")
    messages = [{"role": "user", "content": request.question}]
    if request.stream:
        return StreamingResponse(
            stream_generator(messages),
            media_type="text/plain; charset=utf-8",
            headers=STREAM_HEADERS,
        )

    response = model.create_chat_completion(messages=messages, max_tokens=256)
    answer = response["choices"][0]["message"]["content"]
    return {"question": request.question, "answer": answer}


# Dedicated streaming endpoints for easy integration
@app.get("/ask/stream")
def ask_stream_get(question: str):
    return ask_get(question=question, stream=True)


@app.post("/ask/stream")
def ask_stream_post(request: QueryRequest):
    request.stream = True
    return ask_post(request=request)


