import os
from pathlib import Path
from fastapi import FastAPI, HTTPException
from fastapi.responses import StreamingResponse, HTMLResponse
from pydantic import BaseModel
from llama_cpp import Llama
import uvicorn

app = FastAPI(title="Gemma API")

# Path to the GGUF model file
MODEL_PATH = Path(__file__).resolve().parent / "model" / "google_gemma-4-E4B-it-qat-q4_0-gguf" / "gemma-4-E4B_q4_0-it.gguf"

if not MODEL_PATH.exists():
    raise FileNotFoundError(f"Model file not found at {MODEL_PATH}")

# CPU optimization: On hyperthreaded CPUs, physical cores yield maximum memory bandwidth and throughput.
CPU_COUNT = os.cpu_count() or 4
OPTIMAL_THREADS = max(1, CPU_COUNT // 2)

print(f"Loading model from {MODEL_PATH} with {OPTIMAL_THREADS} generation threads...")
model = Llama(
    model_path=str(MODEL_PATH),
    n_ctx=2048,
    n_threads=OPTIMAL_THREADS,        # Optimal thread count for token generation
    n_threads_batch=CPU_COUNT,        # Use all cores for batch prompt processing
    n_batch=512,                      # Batch size for prompt evaluation
    verbose=False,
)
print("Model loaded successfully!")

# Streaming headers to prevent client and proxy buffering
STREAM_HEADERS = {
    "Cache-Control": "no-cache",
    "Connection": "keep-alive",
    "X-Accel-Buffering": "no",
}


class QueryRequest(BaseModel):
    question: str
    stream: bool = False


def stream_generator(messages):
    """Yields tokens as they are generated by the model."""
    response_stream = model.create_chat_completion(
        messages=messages,
        max_tokens=256,
        stream=True,
    )
    for chunk in response_stream:
        delta = chunk["choices"][0].get("delta", {}).get("content", "")
        if delta:
            yield delta


